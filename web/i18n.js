  const DICTIONARIES = { en: EN, fr: FR, it: IT };

  function known(code) {
    return LANGUAGES.some(([key]) => key === code);
  }

  function stored() {
    try {
      const value = localStorage.getItem(STORAGE_KEY);
      return known(value) ? value : "";
    } catch (error) {
      return "";
    }
  }

  function detect() {
    const wanted = [].concat(navigator.languages || [], navigator.language || []);
    for (const tag of wanted) {
      const code = String(tag).toLowerCase().split("-")[0];
      if (known(code)) return code;
    }
    return "en";
  }

  const lang = stored() || detect();
  const locale = LOCALES[lang];
  document.documentElement.lang = lang;

  function fill(text, values) {
    if (!values) return text;
    return text.replace(/\{(\w+)\}/g, (all, name) => (name in values ? String(values[name]) : all));
  }

  function t(text, values) {
    const table = DICTIONARIES[lang];
    return fill((table && table[text]) || text, values);
  }

  window.InventoryI18n = {
    lang,
    locale,
    languages: LANGUAGES,
    t,
    chosen: () => !!stored(),
    setLang(code) {
      try {
        localStorage.setItem(STORAGE_KEY, code);
      } catch (error) {
        // Without storage the system language stays in use.
      }
    },
  };
